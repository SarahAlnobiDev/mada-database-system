-- 1) DEPARTMENT
CREATE TABLE department (
    department_id    NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    department_name  VARCHAR2(150) NOT NULL,
    department_code  VARCHAR2(30)  NOT NULL,

    CONSTRAINT pk_department PRIMARY KEY (department_id),
    CONSTRAINT uq_department_name UNIQUE (department_name),
    CONSTRAINT uq_department_code UNIQUE (department_code)
);

-- 2) USER_ACCOUNT
CREATE TABLE user_account (
    user_id         NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    full_name       VARCHAR2(200) NOT NULL,
    university_id   VARCHAR2(30),
    email            VARCHAR2(254) NOT NULL,
    password_hash    VARCHAR2(255) NOT NULL,
    role             VARCHAR2(20)  NOT NULL,
    department_id    NUMBER,
    account_status   VARCHAR2(20) DEFAULT 'ACTIVE' NOT NULL,
    created_at       TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,

    CONSTRAINT pk_user_account PRIMARY KEY (user_id),
    CONSTRAINT uq_user_university_id UNIQUE (university_id),
    CONSTRAINT uq_user_email UNIQUE (email),
    CONSTRAINT ck_user_role
        CHECK (role IN ('STUDENT', 'DOCTOR', 'ADMIN')),
    CONSTRAINT ck_user_account_status
        CHECK (account_status IN ('ACTIVE', 'INACTIVE')),
    CONSTRAINT fk_user_department
        FOREIGN KEY (department_id)
        REFERENCES department (department_id)
);

-- 3) COURSE
CREATE TABLE course (
    course_id       NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    course_code     VARCHAR2(30)  NOT NULL,
    course_name     VARCHAR2(150) NOT NULL,
    department_id   NUMBER NOT NULL,
    credit_hours    NUMBER(2) DEFAULT 3 NOT NULL,

    CONSTRAINT pk_course PRIMARY KEY (course_id),
    CONSTRAINT uq_course_code UNIQUE (course_code),
    CONSTRAINT ck_course_credit_hours
        CHECK (credit_hours BETWEEN 1 AND 12),
    CONSTRAINT fk_course_department
        FOREIGN KEY (department_id)
        REFERENCES department (department_id)
);

-- 4) COURSE_ASSIGNMENT
CREATE TABLE course_assignment (
    assignment_id   NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    doctor_id       NUMBER NOT NULL,
    course_id       NUMBER NOT NULL,
    semester        VARCHAR2(20) NOT NULL,
    academic_year   NUMBER(4) NOT NULL,

    CONSTRAINT pk_course_assignment PRIMARY KEY (assignment_id),
    CONSTRAINT uq_course_assignment
        UNIQUE (doctor_id, course_id, semester, academic_year),
    CONSTRAINT ck_assignment_semester
        CHECK (semester IN ('FIRST', 'SECOND', 'SUMMER')),
    CONSTRAINT ck_assignment_year
        CHECK (academic_year BETWEEN 2000 AND 2200),
    CONSTRAINT fk_assignment_doctor
        FOREIGN KEY (doctor_id)
        REFERENCES user_account (user_id),
    CONSTRAINT fk_assignment_course
        FOREIGN KEY (course_id)
        REFERENCES course (course_id)
);

-- 5) PROJECT
CREATE TABLE project (
    project_id            NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    title                 VARCHAR2(250) NOT NULL,
    summary               VARCHAR2(1000),
    problem_statement     CLOB,
    solution_description  CLOB,
    project_type          VARCHAR2(20) NOT NULL,
    academic_status       VARCHAR2(30) DEFAULT 'IN_DEVELOPMENT' NOT NULL,
    workflow_status       VARCHAR2(30) DEFAULT 'NOMINATED' NOT NULL,
    is_featured           NUMBER(1) DEFAULT 0 NOT NULL,
    nomination_reason     VARCHAR2(1000),
    nominated_by          NUMBER NOT NULL,
    created_at            TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    published_at          TIMESTAMP,

    CONSTRAINT pk_project PRIMARY KEY (project_id),
    CONSTRAINT ck_project_type
        CHECK (project_type IN ('COURSE', 'GRADUATION')),
    CONSTRAINT ck_project_academic
        CHECK (academic_status IN
               ('COMPLETED', 'INCOMPLETE', 'IN_DEVELOPMENT')),
    CONSTRAINT ck_project_workflow
        CHECK (workflow_status IN
               ('NOMINATED', 'DRAFT', 'SUBMITTED',
                'REVISION_REQUIRED', 'APPROVED', 'PUBLISHED', 'ARCHIVED')),
    CONSTRAINT ck_project_featured
        CHECK (is_featured IN (0, 1)),
    CONSTRAINT fk_project_nominator
        FOREIGN KEY (nominated_by)
        REFERENCES user_account (user_id)
);

-- 6) COURSE_PROJECT_DETAILS
-- يوجد سجل هنا فقط عندما يكون PROJECT.PROJECT_TYPE = 'COURSE'.
CREATE TABLE course_project_details (
    project_id      NUMBER NOT NULL,
    assignment_id   NUMBER NOT NULL,

    CONSTRAINT pk_course_project_details PRIMARY KEY (project_id),
    CONSTRAINT fk_course_details_project
        FOREIGN KEY (project_id)
        REFERENCES project (project_id)
        ON DELETE CASCADE,
    CONSTRAINT fk_course_details_assign
        FOREIGN KEY (assignment_id)
        REFERENCES course_assignment (assignment_id)
);

-- 7) GRADUATION_PROJECT_DETAILS
-- يوجد سجل هنا فقط عندما يكون PROJECT.PROJECT_TYPE = 'GRADUATION'.
CREATE TABLE graduation_project_details (
    project_id       NUMBER NOT NULL,
    supervisor_id    NUMBER NOT NULL,
    graduation_year  NUMBER(4) NOT NULL,
    project_stage    VARCHAR2(30) DEFAULT 'IN_PROGRESS' NOT NULL,
    defense_date     DATE,

    CONSTRAINT pk_graduation_details PRIMARY KEY (project_id),
    CONSTRAINT ck_graduation_year
        CHECK (graduation_year BETWEEN 2000 AND 2200),
    CONSTRAINT ck_graduation_stage
        CHECK (project_stage IN
               ('IDEA', 'IN_PROGRESS', 'READY', 'DEFENDED', 'ARCHIVED')),
    CONSTRAINT fk_grad_details_project
        FOREIGN KEY (project_id)
        REFERENCES project (project_id)
        ON DELETE CASCADE,
    CONSTRAINT fk_grad_details_supervisor
        FOREIGN KEY (supervisor_id)
        REFERENCES user_account (user_id)
);

-- 8) PROJECT_MEMBER
-- يحوّل العلاقة M:N بين الطالب والمشروع إلى جدول وسيط.
CREATE TABLE project_member (
    project_id                NUMBER NOT NULL,
    student_id                NUMBER NOT NULL,
    member_role               VARCHAR2(100),
    contribution_description  VARCHAR2(1000),
    joined_at                 TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,

    CONSTRAINT pk_project_member PRIMARY KEY (project_id, student_id),
    CONSTRAINT fk_member_project
        FOREIGN KEY (project_id)
        REFERENCES project (project_id)
        ON DELETE CASCADE,
    CONSTRAINT fk_member_student
        FOREIGN KEY (student_id)
        REFERENCES user_account (user_id)
);

-- 9) TECHNOLOGY
CREATE TABLE technology (
    technology_id    NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    technology_name  VARCHAR2(100) NOT NULL,
    category         VARCHAR2(100),

    CONSTRAINT pk_technology PRIMARY KEY (technology_id),
    CONSTRAINT uq_technology_name UNIQUE (technology_name)
);

-- 10) PROJECT_TECHNOLOGY
-- يحوّل العلاقة M:N بين المشروع والتقنية إلى جدول وسيط.
CREATE TABLE project_technology (
    project_id      NUMBER NOT NULL,
    technology_id   NUMBER NOT NULL,
    usage_note      VARCHAR2(500),

    CONSTRAINT pk_project_technology
        PRIMARY KEY (project_id, technology_id),
    CONSTRAINT fk_project_tech_project
        FOREIGN KEY (project_id)
        REFERENCES project (project_id)
        ON DELETE CASCADE,
    CONSTRAINT fk_project_tech_tech
        FOREIGN KEY (technology_id)
        REFERENCES technology (technology_id)
);

-- 11) PROJECT_FILE
-- في نسخة المعرض نخزن بيانات الملف أو الرابط، وليس الملف نفسه داخل الجدول.
CREATE TABLE project_file (
    file_id          NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    project_id       NUMBER NOT NULL,
    uploaded_by      NUMBER NOT NULL,
    file_name        VARCHAR2(255) NOT NULL,
    file_type        VARCHAR2(50)  NOT NULL,
    file_url         VARCHAR2(1000) NOT NULL,
    access_level     VARCHAR2(20) DEFAULT 'PUBLIC' NOT NULL,
    file_size_kb     NUMBER(12,2),
    uploaded_at      TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,

    CONSTRAINT pk_project_file PRIMARY KEY (file_id),
    CONSTRAINT ck_file_access_level
        CHECK (access_level IN ('PUBLIC', 'RESTRICTED')),
    CONSTRAINT ck_file_size
        CHECK (file_size_kb IS NULL OR file_size_kb >= 0),
    CONSTRAINT fk_file_project
        FOREIGN KEY (project_id)
        REFERENCES project (project_id)
        ON DELETE CASCADE,
    CONSTRAINT fk_file_uploader
        FOREIGN KEY (uploaded_by)
        REFERENCES user_account (user_id)
);

-- 12) PROJECT_PASSPORT
-- علاقة 1 : 0..1 لأن المشروع قد لا يكون موثقاً بالكامل بعد.
CREATE TABLE project_passport (
    project_id                NUMBER NOT NULL,
    working_features          CLOB,
    incomplete_parts          CLOB,
    source_code_availability  VARCHAR2(20) DEFAULT 'ON_REQUEST' NOT NULL,
    accepts_continuation      NUMBER(1) DEFAULT 1 NOT NULL,
    future_ideas              CLOB,
    updated_at                TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,

    CONSTRAINT pk_project_passport PRIMARY KEY (project_id),
    CONSTRAINT ck_passport_code
        CHECK (source_code_availability IN
               ('PUBLIC', 'ON_REQUEST', 'PRIVATE')),
    CONSTRAINT ck_passport_continuation
        CHECK (accepts_continuation IN (0, 1)),
    CONSTRAINT fk_passport_project
        FOREIGN KEY (project_id)
        REFERENCES project (project_id)
        ON DELETE CASCADE
);

-- 13) REVIEW
CREATE TABLE review (
    review_id        NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    project_id       NUMBER NOT NULL,
    reviewer_id      NUMBER NOT NULL,
    review_decision  VARCHAR2(30) NOT NULL,
    comments         VARCHAR2(2000),
    review_date      TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    round_number     NUMBER(3) DEFAULT 1 NOT NULL,

    CONSTRAINT pk_review PRIMARY KEY (review_id),
    CONSTRAINT uq_review_round
        UNIQUE (project_id, reviewer_id, round_number),
    CONSTRAINT ck_review_decision
        CHECK (review_decision IN
               ('PENDING', 'REVISION_REQUIRED', 'APPROVED', 'REJECTED')),
    CONSTRAINT ck_review_round
        CHECK (round_number >= 1),
    CONSTRAINT fk_review_project
        FOREIGN KEY (project_id)
        REFERENCES project (project_id)
        ON DELETE CASCADE,
    CONSTRAINT fk_review_reviewer
        FOREIGN KEY (reviewer_id)
        REFERENCES user_account (user_id)
);

-- 14) PROJECT_RELATION
-- يربط المشروع الأصلي بالمشروع الذي طوره في سنة لاحقة.
CREATE TABLE project_relation (
    relation_id          NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    parent_project_id    NUMBER NOT NULL,
    child_project_id     NUMBER NOT NULL,
    relation_type        VARCHAR2(30) DEFAULT 'EXTENDS' NOT NULL,
    relation_description VARCHAR2(1000),
    created_at           TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,

    CONSTRAINT pk_project_relation PRIMARY KEY (relation_id),
    CONSTRAINT uq_project_relation
        UNIQUE (parent_project_id, child_project_id, relation_type),
    CONSTRAINT ck_relation_projects
        CHECK (parent_project_id <> child_project_id),
    CONSTRAINT ck_relation_type
        CHECK (relation_type IN
               ('EXTENDS', 'CONTINUATION', 'INSPIRED_BY')),
    CONSTRAINT fk_relation_parent
        FOREIGN KEY (parent_project_id)
        REFERENCES project (project_id)
        ON DELETE CASCADE,
    CONSTRAINT fk_relation_child
        FOREIGN KEY (child_project_id)
        REFERENCES project (project_id)
        ON DELETE CASCADE
);

